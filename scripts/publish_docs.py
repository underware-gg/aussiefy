import argparse
from bisect import bisect_right
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
import posixpath
import re
import sys
import unicodedata
from urllib.parse import quote, unquote, urlsplit

import yaml
from markdown_it import MarkdownIt
from markdown_it.helpers import parseLinkDestination, parseLinkLabel
from markdown_it.rules_inline.state_inline import StateInline

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from aussiefy.engine import Translator  # noqa: E402
from aussiefy.markdown import html_tag_pattern, inline_link_end  # noqa: E402
from aussiefy.scrape.fetch import save_text  # noqa: E402
