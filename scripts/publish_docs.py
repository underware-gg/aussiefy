from markdown_it.helpers import parseLinkDestination, parseLinkLabel
from markdown_it.rules_inline.state_inline import StateInline

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import aussiefy  # noqa: E402
from aussiefy.engine import Translator  # noqa: E402
from aussiefy.errors import UserError  # noqa: E402
from aussiefy.markdown import html_tag_pattern, inline_link_end  # noqa: E402
from aussiefy.policy import (EMBELLISHMENT_NAMES, LEVEL_NAMES, VULGARITY_NAMES, Policy,  # noqa: E402
                             parse_embellishment, parse_vulgarity)
from aussiefy.scrape.fetch import save_text  # noqa: E402
from aussiefy.translation import run  # noqa: E402

CONFIG = "docs/publication.yaml"
TRANSLATION = ("level", "vulgarity", "seed", "embellishment", "document_type", "document_config")
LABELS = {"tourist": "Tourist", "blow-in": "Blow-in", "local": "Local", "larrikin": "Larrikin", "swaggie": "Swaggie",
          "nan": "Nan", "dad": "Dad", "uncle-bob": "Uncle Bob", "tradie": "Tradie",
          "deadset": "Deadset", "dinkum": "Dinkum", "troppo": "Troppo"}
MARKER = "<!-- Generated by scripts/publish_docs.py; edit the linked plain source. -->"
HISTORICAL = ("docs/architecture/reviews/design-review-", "docs/architecture/decisions/dd-",
              "docs/standards/agent-ready-documentation.md")


class PublicationError(ValueError):
    """An invalid source, map, link or stale generated document."""


@dataclass(frozen=True)
class Document:
    source: str
    output: str


@dataclass(frozen=True)
class Publication:
    documents: tuple[Document, ...]
    level: int
    vulgarity: str
    seed: int
    embellishment: str
    document_type: str
    document_config: dict

    @property
    def outputs(self) -> dict[str, str]:
        return {d.source: d.output for d in self.documents}

    @property
    def sources(self) -> dict[str, str]:
        return {d.output: d.source for d in self.documents}

    @property
    def settings(self) -> dict:
        return {k: getattr(self, k) for k in TRANSLATION}

    def notice(self, plain: str) -> str:
        """The settings line every published page opens with, linking to its plain counterpart."""
        level, embellishment, vulgarity = _labels(self.settings)
        return (f"> Aussiefied at **{level}** level, with **{embellishment}** embellishment and **{vulgarity}** "
                f"vulgarity. [Prefer docs that are as dry as a dead dingo's donger?]({plain})")


def _labels(settings: dict) -> tuple[str, str, str]:
    stops = (LEVEL_NAMES[settings["level"]], settings["embellishment"], settings["vulgarity"])
    missing = [stop for stop in stops if stop not in LABELS]
    if missing:
        raise PublicationError(f"no notice label for {', '.join(missing)}: add it to LABELS")
    return tuple(LABELS[stop] for stop in stops)


def _relative(value, where: str) -> str:
    if not isinstance(value, str) or not value:
        raise PublicationError(f"{where}: expected a repository-relative path")
    if any(ord(c) < 32 for c in value):
        raise PublicationError(f"{where}: control characters are not valid paths")
    path = PurePosixPath(value)
    if path.is_absolute() or ".." in path.parts or "\\" in value or path.as_posix() != value or path.suffix != ".md":
        raise PublicationError(f"{where}: expected a normalised relative Markdown path")
    return value


def _file(root: Path, name: str) -> Path:
    path = root / name
    if path.is_symlink() or not path.resolve().is_relative_to(root.resolve()) or not path.is_file():
        raise PublicationError(f"{name}: expected an ordinary file inside the repository")
    return path


def read(root: Path, name: str) -> str:
    try:
        with _file(root, name).open(encoding="utf-8", newline="") as source:
            return source.read()
    except (OSError, UnicodeError) as exc:
        raise PublicationError(f"{name}: could not read UTF-8 text: {exc}") from exc


def _translation(settings, where: str) -> dict:
    """A validated copy of the settings publication fixes, with vulgarity and embellishment by stop name.

    Each is named, so the notice can say what the pages were translated at."""
    if not isinstance(settings, dict) or set(settings) != set(TRANSLATION):
        raise PublicationError(f"{where}: translation needs exactly {', '.join(TRANSLATION)}")
    if any(type(settings[k]) is not int for k in ("level", "seed")):
        raise PublicationError(f"{where}: level and seed must be integers")
    settings = copy.deepcopy(settings)
    try:
        settings["vulgarity"] = VULGARITY_NAMES[parse_vulgarity(settings["vulgarity"])]
        settings["embellishment"] = EMBELLISHMENT_NAMES[parse_embellishment(settings["embellishment"])]
        Policy(**settings)
    except UserError as exc:
        raise PublicationError(f"{where}: {exc}") from exc
    _labels(settings)
    return settings


def _overlay(base: dict, overlay: dict) -> dict:
    """Maps merge key by key; anything else, a list included, replaces. The caller copies the result."""
    merged = dict(base)
    for key, value in overlay.items():
        inherited = base.get(key)
        merged[key] = _overlay(inherited, value) if isinstance(value, dict) and isinstance(inherited, dict) else value
    return merged


def load(root: Path) -> Publication:
    try:
        data = yaml.safe_load(read(root, CONFIG))
    except yaml.YAMLError as exc:
        raise PublicationError(f"{CONFIG}: invalid YAML: {exc}") from exc
    if not isinstance(data, dict) or set(data) != {"translation", "documents"}:
        raise PublicationError(f"{CONFIG}: expected translation and documents")
    settings = _translation(data["translation"], CONFIG)
    rows = data["documents"]
    if not isinstance(rows, list) or not rows:
        raise PublicationError(f"{CONFIG}: documents must be a non-empty list")
    docs = []
    for row in rows:
        if not isinstance(row, dict) or set(row) != {"source", "output"}:
            raise PublicationError(f"{CONFIG}: each document needs source and output")
        source = _relative(row["source"], "source")
        output = _relative(row["output"], "output")
        if not source.startswith("docs/plain/"):
            raise PublicationError(f"{source}: authoritative sources belong under docs/plain/")
        if (output not in ("README.md", "CONTRIBUTING.md", "CHANGELOG.md") and not output.startswith("docs/")) or output.startswith("docs/plain/") or output.startswith(HISTORICAL):
            raise PublicationError(f"{output}: not a public documentation destination")
        docs.append(Document(source, output))
    if len({d.source for d in docs}) != len(docs) or len({d.output for d in docs}) != len(docs):
        raise PublicationError(f"{CONFIG}: duplicate source or output")
    return Publication(tuple(docs), **settings)


def with_settings(publication: Publication, *, vulgarity: int | str | None = None,
                  document_config_overlay: dict | None = None) -> Publication:
    """The publication at a caller's vulgarity, with an overlay merged onto its document_config."""
    settings = publication.settings
    if vulgarity is not None:
        settings["vulgarity"] = vulgarity
    if document_config_overlay is not None:
        if not isinstance(document_config_overlay, dict):
            raise PublicationError("document_config_overlay must be a mapping")
        settings["document_config"] = _overlay(settings["document_config"] or {}, document_config_overlay)
    return replace(publication, **_translation(settings, "caller settings"))


def destinations(text: str):
    """Source ranges of inline/image/reference destinations, using the parser's destination grammar."""
    parser = MarkdownIt("commonmark").enable("table")
    env = {}
    tokens = parser.parse(text, env)
    starts = [0] + [m.end() for m in re.finditer("\n", text)]
    end_line = lambda n: starts[n] if n < len(starts) else len(text)
    blocked = [(starts[t.map[0]], end_line(t.map[1])) for t in tokens
               if t.type in ("fence", "code_block", "html_block") and t.map]
    reference_ends = {r["map"][0]: end_line(r["map"][1]) for r in env.get("references", {}).values()}
    inline = [(starts[t.map[0]], end_line(t.map[1])) for t in tokens if t.type == "inline" and t.map]
    skip_to = {}
    state = StateInline(text, parser, {}, [])
    tags = html_tag_pattern()
    i = block = 0
    while i < len(text):
        if i in skip_to:
            i = skip_to[i]
            continue
        while block < len(blocked) and blocked[block][1] <= i:
            block += 1
        if block < len(blocked) and blocked[block][0] <= i < blocked[block][1]:
            i = blocked[block][1]
            continue
        if text[i] == "\\":
            i += 2
            continue
        if text[i] == "`":
            ticks = re.match(r"`+", text[i:])[0]
            limit = next((end for start, end in inline if start <= i < end), end_line(bisect_right(starts, i)))
            close = re.compile(r"(?<!`)" + re.escape(ticks) + r"(?!`)").search(text, i + len(ticks), limit)
            i = close.end() if close else i + len(ticks)
            continue
        if text[i] == "<":
            tag = tags.match(text, i)
            if tag:
                i = tag.end()
                continue
        if text[i] == "[":
            close = parseLinkLabel(state, i)
            if close >= 0:
                after = close + 1
                if text[after:after + 1] == "(" or (text[after:after + 1] == ":" and bisect_right(starts, i) - 1 in reference_ends):
                    begin = after + 1
                    while begin < len(text) and text[begin].isspace():
                        begin += 1
                    dest = parseLinkDestination(text, begin, len(text))
                    if dest.ok and parser.validateLink(parser.normalizeLink(dest.str)):
                        tail = dest.pos
                        if text[after] == ":":
                            tail = reference_ends[bisect_right(starts, i) - 1]
                        else:
                            tail = inline_link_end(text, after)
                            if tail is None:
                                i += 1
                                continue
                        skip_to[after + 1] = tail
                        yield begin, dest.pos, dest.str
        i += 1


def _url(href: str):
    try:
        return urlsplit(href)
    except ValueError as exc:
        raise PublicationError(f"invalid link destination {href!r}: {exc}") from exc


def remap_links(text: str, previous: str, current: str, mapping: dict[str, str]) -> str:
    edits = []
    for start, end, href in destinations(text):
        url = _url(href)
        if url.scheme or url.netloc or not url.path:
            continue
        target = posixpath.normpath(posixpath.join(posixpath.dirname(previous), unquote(url.path)))
        target = mapping.get(target, target)
        relative = posixpath.relpath(target, posixpath.dirname(current) or ".")
        literal = text[start:end].removeprefix("<").removesuffix(">")
        delimiter = re.search(r"[?#]", literal)
        suffix = literal[delimiter.start():] if delimiter else ""
        replacement = quote(relative, safe="/._-~") + suffix
        if text[start:end].startswith("<"):
            replacement = "<" + replacement + ">"
        edits.append((start, end, replacement))
    for start, end, replacement in sorted(edits, reverse=True):
        text = text[:start] + replacement + text[end:]
    return text


def anchors(text: str) -> set[str]:
    tokens = MarkdownIt("commonmark").enable("table").parse(text)
    seen, result = set(), set()
    for i, token in enumerate(tokens):
        if token.type == "heading_open":
            title = "".join(c.content for c in tokens[i + 1].children or [] if c.type in ("text", "code_inline", "image"))
            base = "".join(c for c in title.lower() if c in "_-" or not unicodedata.category(c).startswith(("P", "S", "C"))).replace(" ", "-")
            slug, n = base, 0
            while slug in seen:
                n += 1
                slug = f"{base}-{n}"
            result.add(slug)
            seen.add(slug)
        if token.type in ("html_inline", "html_block"):
            result.update(re.findall(r'(?:id|name)=["\']([^"\']+)', token.content))
        for child in token.children or []:
            if child.type == "html_inline":
                result.update(re.findall(r'(?:id|name)=["\']([^"\']+)', child.content))
    return result


def check_links(root: Path, paths: list[str]) -> None:
    errors, cache = [], {}
    for name in paths:
        for _, _, href in destinations(read(root, name)):
            url = _url(href)
            if url.scheme or url.netloc:
                continue
            if "\0" in unquote(url.path):
                raise PublicationError(f"{name}: invalid local destination {href!r}: embedded NUL")
            target = root / posixpath.normpath(posixpath.join(posixpath.dirname(name), unquote(url.path))) if url.path else root / name
            if not target.resolve().is_relative_to(root.resolve()) or not target.exists():
                errors.append(f"{name}: missing repository target {href}")
            elif url.fragment and target.suffix == ".md":
                target_name = target.relative_to(root).as_posix()
                if target_name not in cache:
                    cache[target_name] = anchors(read(root, target_name))
                if unquote(url.fragment) not in cache[target_name]:
                    errors.append(f"{name}: missing anchor {href}")
    if errors:
        raise PublicationError("\n".join(errors))


def authoritative_docs(root: Path, publication: Publication) -> list[str]:
    """Each editable source and ungenerated current document once; never a source and its published copy."""
    outputs = set(publication.sources)
    paths = {d.source for d in publication.documents}
    paths.update(p.relative_to(root).as_posix() for directory in ("docs", "skills") for p in (root / directory).rglob("*.md")
                 if p.relative_to(root).as_posix() not in outputs
                 and not p.relative_to(root).as_posix().startswith(HISTORICAL))
    return sorted(paths)


def build(root: Path, publication: Publication) -> dict[str, str]:
    sources = {d.source for d in publication.documents}
    actual = {p.relative_to(root).as_posix() for p in (root / "docs/plain").rglob("*.md")}
    if actual != sources:
        raise PublicationError(f"plain sources differ from the map: {sorted(actual ^ sources)}")
    translator = Translator()
    outputs = {}
    for document in publication.documents:
        source = read(root, document.source)
        if source.startswith(MARKER):
            raise PublicationError(f"{document.source}: a generated copy is not a plain source")
        mapped = remap_links(source, document.source, document.output, publication.outputs)
        result = run(mapped, translator=translator, markdown=True, embedder="ngram", **publication.settings)
        relative = posixpath.relpath(document.source, posixpath.dirname(document.output) or ".")
        outputs[document.output] = f"{MARKER}\n\n{publication.notice(relative)}\n\n{result.text}"
    return outputs


def kept_plain(root: Path) -> list[str]:
    """Current Markdown documents publication never translates: ADRs, historical reviews and the copied standard."""
    return sorted(p.relative_to(root).as_posix() for p in (root / "docs").rglob("*.md")
                  if p.relative_to(root).as_posix().startswith(HISTORICAL))


def _save(destination: Path, outputs: dict[str, str]) -> None:
    for name in outputs:
        target = destination / name
        if target.is_symlink() or (target.exists() and not target.is_file()) or not target.resolve().is_relative_to(destination.resolve()):
            raise PublicationError(f"{name}: output must stay inside {destination}")
    for name, text in outputs.items():
        target = destination / name
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            save_text(target, text)
        except OSError as exc:
            raise PublicationError(f"{name}: could not save generated prose: {exc}") from exc


def generate(root: Path) -> None:
    publication = load(root)
    outputs = build(root, publication)
    check_links(root, [d.source for d in publication.documents])
    _save(root, outputs)
    check_links(root, list(outputs))


def export(root: Path, out_dir: Path, *, vulgarity: int | str | None = None,
           document_config_overlay: dict | None = None) -> Publication:
    """Publish a variant into a new or empty out_dir outside the repository, at each document's public path.

    Its links stay relative to each page's place in the repository's public tree. The returned publication pairs
    each source with its output and carries the settings the variant used."""
    engine = Path(aussiefy.__file__).resolve().parent
    if engine != (root / "aussiefy").resolve():
        raise PublicationError(f"export must run the repository's own engine, not {engine}: "
                               "run scripts/publish_docs.py export from that checkout, in its own process")
    out = out_dir.resolve()
    if out.is_relative_to(root.resolve()) or (out.exists() and (not out.is_dir() or any(out.iterdir()))):
        raise PublicationError(f"{out_dir}: export needs a new or empty directory outside the repository")
    publication = with_settings(load(root), vulgarity=vulgarity, document_config_overlay=document_config_overlay)
    outputs = build(root, publication)
    check_links(root, [d.source for d in publication.documents])
    _save(out, outputs)
    return publication


def manifest(root: Path, publication: Publication) -> dict:
    """What a host needs to place the exported pages and rewrite their links (DD-038)."""
    return {"settings": publication.settings,
            "documents": [{"source": d.source, "output": d.output} for d in publication.documents],
            "kept_plain": kept_plain(root)}


def _read_overlay(path: Path) -> dict:
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, yaml.YAMLError) as exc:
        raise PublicationError(f"{path}: could not read the document_config overlay: {exc}") from exc


def check(root: Path) -> None:
    publication = load(root)
    expected = build(root, publication)
    errors = [f"{name}: generated prose is stale; run python scripts/publish_docs.py generate"
              for name, text in expected.items() if not (root / name).is_file() or read(root, name) != text]
    candidates = [*root.glob("*.md"), *(root / "docs").rglob("*.md")]
    errors += [f"{p.relative_to(root)}: unexpected generated output" for p in candidates
               if p.relative_to(root).as_posix() not in expected and read(root, p.relative_to(root).as_posix()).startswith(MARKER)]
    if errors:
        raise PublicationError("\n".join(errors))
    check_links(root, [d.source for d in publication.documents] + list(expected))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", choices=("generate", "check", "export"))
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--out", type=Path, help="export: a new or empty directory for the pages")
    parser.add_argument("--vulgarity", help="export: the variant's vulgarity (default: the publication's)")
    parser.add_argument("--overlay", type=Path, help="export: a YAML or JSON document_config overlay file")
    args = parser.parse_args(argv)
    variant = (args.out, args.vulgarity, args.overlay)
    if args.command == "export" and args.out is None:
        parser.error("export needs --out")
    if args.command != "export" and any(v is not None for v in variant):
        parser.error("--out, --vulgarity and --overlay belong to export")
    root = args.root.resolve()
    try:
        if args.command == "export":
            overlay = None if args.overlay is None else _read_overlay(args.overlay)
            publication = export(root, args.out, vulgarity=args.vulgarity, document_config_overlay=overlay)
            print(json.dumps(manifest(root, publication), indent=2))
            return 0
        {"generate": generate, "check": check}[args.command](root)
    except PublicationError as exc:
        print(f"publish-docs: {exc}", file=sys.stderr)
        return 1
    print(f"Documentation {args.command} passed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
