"""Publish deterministic Aussie documentation from authoritative plain sources.

    python scripts/publish_docs.py generate
    python scripts/publish_docs.py check
    python scripts/publish_docs.py export --out DIR [--vulgarity V] [--overlay FILE]

`export` is how a host (the website) publishes the docs in its own voice from a checkout of a tagged release.
It writes the pages into DIR and prints a JSON manifest (DD-038).
"""

