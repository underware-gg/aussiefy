"""Regenerate tests/corpus/golden.yaml from tests/corpus/sentences.txt and tests/corpus/reference/*.txt.

Run after an intentional change to the engine or dictionary, then review the
diff of golden.yaml like any other code change:

    python scripts/regen_golden.py && git diff tests/corpus/golden.yaml
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from aussiefy import Translator  # noqa: E402
from aussiefy.dump import dump_yaml  # noqa: E402

CORPUS = ROOT / "tests" / "corpus"
SEEDS = (0, 1)
LEVELS = (1, 2, 3, 4, 5)


def sentences() -> list[str]:
    lines = (CORPUS / "sentences.txt").read_text(encoding="utf-8").splitlines()
    return [ln.strip() for ln in lines if ln.strip() and not ln.startswith("#")]


def references() -> list[str]:
    return [p.read_text(encoding="utf-8") for p in sorted((CORPUS / "reference").glob("*.txt"))]


def build(translator: Translator | None = None) -> list[dict]:
    tr = translator or Translator()
    out = []
    for text, seeds in [(t, SEEDS) for t in sentences()] + [(t, (0,)) for t in references()]:
        outputs = {}
        for level in LEVELS:
            for seed in seeds:
                outputs[f"L{level}s{seed}"] = tr.translate(text, level=level, seed=seed).text
        out.append({"input": text, "outputs": outputs})
    return out


if __name__ == "__main__":
    golden = build()
    header = "# Generated by scripts/regen_golden.py. Do not edit by hand.\n"
    (CORPUS / "golden.yaml").write_text(header + dump_yaml(golden), encoding="utf-8")
    print(f"wrote {len(golden)} inputs x {len(LEVELS) * len(SEEDS)} outputs")
