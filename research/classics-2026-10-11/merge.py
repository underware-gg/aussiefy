"""Merge the classics round's sources into verifier candidates.

    python3 research/classics-2026-10-11/merge.py

Sources: the two extractors (extract/{X,Y}/terms.yaml), the user's seed terms (seeds.yaml) and the phrases the
unharnessed retellings used (../retellings-2026-10-11/new_phrases.yaml). Terms are keyed by a normalised form
(lower case, no leading article, "-in'" as "-ing", possessives dropped in phrases), so "the cracks" and "crack" stay apart but "spruikin'" and
"spruiking" merge. Offensive terms are dropped here and listed in dropped.yaml. A term whose key matches an
existing dictionary form is kept, marked `in_dictionary` with the entry ids, so the verifier can check the existing
entry's sense against the classic usage instead of adding a duplicate.

Writes merged.yaml (every term) and verify/candidates-{1,2,3}.yaml (three slices of about equal size, seeds first).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))

from aussiefy.loader import load_dictionary  # noqa: E402


def key(t: str) -> str:
    t = re.sub(r"\{[a-z]+\}", "", str(t).lower().replace("’", "'"))
    t = re.sub(r"\b(\w+)in'(?=\s|$)", r"\1ing", t)
    # possessives stand for the {poss} slot: "do your block" matches "do {poss} block"
    t = re.sub(r"\b(my|me|your|yer|his|her|their|our|one's)\b", " ", t) if " " in t.strip() else t
    t = re.sub(r"\s+", " ", re.sub(r"^(a|an|the) ", "", t.strip())).strip(" .!?,'\"")
    return t


def main() -> int:
    d = load_dictionary()
    form_ids: dict[str, list[str]] = {}
    for e in d.entries.values():
        for f in e.all_forms:
            form_ids.setdefault(key(re.sub(r"(\w+)\|\w+", r"\1", f)), []).append(e.id)

    merged: dict[str, dict] = {}
    dropped = []

    def add(term: str, record: dict, priority: int = 1) -> None:
        k = key(term)
        if not k:
            return
        c = merged.setdefault(k, {"term": term, "priority": priority, "records": []})
        c["priority"] = min(c["priority"], priority)
        c["records"].append(record)

    seeds = yaml.safe_load((HERE / "seeds.yaml").read_text()) or []
    for s in seeds:
        add(s["term"], {"origin": "user_seed", "source": s.get("source"), "guidance": s.get("guidance")}, 0)
    for ex in ("X", "Y"):
        for t in yaml.safe_load((HERE / "extract" / ex / "terms.yaml").read_text()) or []:
            if t.get("offensive"):
                dropped.append({"term": t["term"], "origin": f"extractor_{ex}", "reason": "offensive"})
                continue
            rec = {"origin": f"extractor_{ex}", **{k: t.get(k) for k in (
                "text", "line", "as_printed", "kind", "meaning", "plain", "frame", "register", "still_heard",
                "confidence", "notes") if t.get(k) not in (None, "", [])}}
            add(t["term"], rec)
    for p in yaml.safe_load((HERE.parent / "retellings-2026-10-11" / "new_phrases.yaml").read_text()) or []:
        rec = {"origin": "unharnessed_retelling", **{k: p.get(k) for k in (
            "texts", "kind", "meaning", "plain", "confidence", "note") if p.get(k) not in (None, "", [])}}
        add(p["phrase"], rec)

    out = []
    for k, c in merged.items():
        origins = sorted({r["origin"] for r in c["records"]})
        item = {"term": c["term"], "key": k, "origins": origins}
        if k in form_ids:
            item["in_dictionary"] = sorted(set(form_ids[k]))
        item["records"] = c["records"]
        item["_priority"] = c["priority"]
        out.append(item)
    # seeds first, then terms several sources agree on, then the rest; alphabetical within
    out.sort(key=lambda i: (i["_priority"], -len(i["origins"]), i["key"]))
    for i in out:
        del i["_priority"]

    (HERE / "merged.yaml").write_text(
        "# All classics-round terms, merged by normalised key (see merge.py). Generated: don't edit.\n"
        + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=110))
    (HERE / "dropped.yaml").write_text(
        "# Dropped before verification (offensive historical terms are listed by name only).\n"
        + yaml.safe_dump(dropped, sort_keys=False, allow_unicode=True))
    slices = [out[i::3] for i in range(3)]   # round-robin keeps seeds and multi-source terms spread across slices
    for n, sl in enumerate(slices, 1):
        (HERE / "verify" / f"candidates-{n}.yaml").write_text(
            f"# Verifier slice {n} of 3 (generated by merge.py).\n"
            + yaml.safe_dump(sl, sort_keys=False, allow_unicode=True, width=110))
    in_dict = sum(1 for i in out if "in_dictionary" in i)
    multi = sum(1 for i in out if len(i["origins"]) > 1)
    print(f"{len(out)} terms ({in_dict} already in the dictionary, {multi} from 2+ sources), "
          f"{len(dropped)} dropped; slices: {[len(s) for s in slices]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
